# 주의
#   두 함수의 버그는 서로 다른 종류입니다.
#     find_max   → 보는 "범위"의 문제
#     count_pass → "부등호"의 문제
#
# 그리고 이번 주에서 가장 중요한 사실
#   데이터를 바꾸면 우연히 정답이 나옵니다.  아래를 직접 실행해 보세요.
#     find_max([95, 85, 70, 60])   → 95   (맞음! 우연히)
#     find_max([10, 20, 30])       → 20   (틀림)
#     count_pass([70, 85, 95])     → 3    (맞음! 경계값이 없어서)
#     count_pass([60, 60, 59])     → 0    (틀림, 2여야 함)
#   → 테스트 하나 통과는 정확성의 증거가 아닙니다.
#     회귀 검증에는 반드시 "경계값(60 자체)"을 넣으세요.
# ---------------------------------------------------------------------------

def find_max(scores):
    biggest = scores[0]
    for i in range(1, len(scores) - 1):
        if scores[i] > biggest:
            biggest = scores[i]
    return biggest


def count_pass(scores, cutoff=60):
    n = 0
    for s in scores:
        if s > cutoff:
            n += 1
    return n


data = [70, 85, 60, 95]
print("최고점:", find_max(data))
print("합격자:", count_pass(data))
