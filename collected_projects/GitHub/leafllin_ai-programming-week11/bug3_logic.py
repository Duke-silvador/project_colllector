#   2. 실제 출력과 비교해 기록지 ①에 증상을 적는다.
#   3. 가설을 한 문장으로 기록지 ③에 적는다.  ("X 때문일 것이다")
#   4. 아래 관찰을 하나만 넣어 가설을 확인한다.
