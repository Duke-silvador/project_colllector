_BY_CODE = {c: (c, n, a) for c, n, a in STORES}


def label(code):
    """Название для списков и поля «Филиал»: «01 Мирабад»."""
    s = _BY_CODE.get(code)
    return "%s %s" % (s[0], s[1]) if s else ""


def place(code):
    """Строка для сообщения кандидату: магазин и полный адрес."""
    s = _BY_CODE.get(code)
    return "Texnomart %s. %s" % (s[1], s[2]) if s else ""


def resolve(text):
    """Находит магазин по номеру («7», «07»), по подписи («07 Чиланзар») или по точному названию. Код или None."""
    t = re.sub(r"\s+", " ", str(text or "")).strip().lower()
    if not t:
        return None
    if re.fullmatch(r"\d{1,2}", t) and t.zfill(2) in _BY_CODE:
        return t.zfill(2)
    for c, n, _a in STORES:
        if t in (n.lower(), label(c).lower()):
            return c
    return None


