// Helper to look up language by code
function getLanguageByCode(code) {
  if (code === 'auto') return { code: 'auto', name: 'Detect Language', native: 'Auto Detect', flag: '🌐', speech: 'en-US' };
  return LANGUAGES.find(lang => lang.code.toLowerCase() === code.toLowerCase()) || {
    code: code,
    name: code,
    native: code,
    flag: '🌐',
    speech: code
  };
}
